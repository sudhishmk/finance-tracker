package com.sudhi.financetracker.app.mapper;

import com.sudhi.financetracker.finance.model.Expense;
import com.sudhi.financetracker.app.rest.ExpenseRequest;

public class ExpenseMapper {

    public static Expense toDomain(ExpenseRequest req) {
        return new Expense(
                null,  // ID will be generated by the database
                req.date,
                req.description,
                req.amount,
                req.category,
                req.paymentMode,
                req.account,
                req.valueScore
        );
    }
}
